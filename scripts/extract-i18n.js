#!/usr/bin/env node
// Scans JS and HTML source files for translatable strings and writes extension/i18n/en.js.
// Sources:
//   - JS files: t("...") and t('...') calls
//   - HTML files: data-i18n="...", data-i18n-aria-label="...", data-i18n-title="...", etc.
//
// Usage: node scripts/extract-i18n.js

const fs = require("fs");
const path = require("path");

const SOURCE_FILES = [
  "extension/popup.js",
  "extension/settings.js",
  "extension/setup.js",
  "extension/popup.html",
  "extension/settings.html",
  "extension/setup.html"
];

const OUTPUT_FILE = "extension/i18n/en.js";

function extractFromJs(src) {
  const keys = new Set();
  // Match t("...") or t('...') — single-level string literals only
  const re = /\bt\(\s*(["'])((?:[^"'\\]|\\.)*?)\1/g;
  let m;
  while ((m = re.exec(src)) !== null) {
    const key = m[2].replace(/\\(["'\\])/g, "$1");
    if (key.trim()) keys.add(key);
  }
  return keys;
}

function extractFromHtml(src) {
  const keys = new Set();
  // data-i18n="..." and data-i18n-*="..."
  const re = /\bdata-i18n(?:-[a-z-]+)?="([^"]*)"/g;
  let m;
  while ((m = re.exec(src)) !== null) {
    const key = m[1];
    if (key.trim()) keys.add(key);
  }
  return keys;
}

const allKeys = new Set();
for (const relPath of SOURCE_FILES) {
  const abs = path.join(process.cwd(), relPath);
  if (!fs.existsSync(abs)) {
    console.warn(`WARN: not found: ${relPath}`);
    continue;
  }
  const src = fs.readFileSync(abs, "utf-8");
  const keys = relPath.endsWith(".html") ? extractFromHtml(src) : extractFromJs(src);
  for (const k of keys) allKeys.add(k);
}

// Sort keys for stable output
const sorted = [...allKeys].sort((a, b) => a.localeCompare(b, "en"));

const lines = sorted.map((key) => {
  // Escape backslashes and double-quotes in the key
  const escaped = key.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  return `      "${escaped}": ""`;
});

const output = `// English — source of truth for all translation keys.
// Generated by scripts/extract-i18n.js — do not hand-edit.
// Run: npm run extract:i18n
module.exports = {
  // prettier-ignore
  static: {
${lines.join(",\n")}
  },
};
`;

const outPath = path.join(process.cwd(), OUTPUT_FILE);
fs.writeFileSync(outPath, output, "utf-8");
console.log(`Wrote ${sorted.length} keys to ${OUTPUT_FILE}`);
